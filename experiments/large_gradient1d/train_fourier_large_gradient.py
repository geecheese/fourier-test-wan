#!/usr/bin/env python3
"""Train and audit Model Problem 2: a 1D large-gradient transition layer.

The exact Dirichlet solution is
``u*(x) = x (pi-x) tanh(beta (x-pi/2))``.  The forcing is generated by
automatic differentiation, and each modes setting minimizes the truncated
Fourier ``H^{-1}`` dual norm of the strong residual on a uniform interior grid.

Objective classification: strong residual projection, not explicit weak moments.
"""

from __future__ import annotations

import argparse
import json
import math
import time
from pathlib import Path

import torch
from torch import nn

from src.methods.fourier_test_space import FourierDualLoss


PI = math.pi


class TrialNet(nn.Module):
    def __init__(self, width: int = 48, depth: int = 3) -> None:
        super().__init__()
        layers: list[nn.Module] = [nn.Linear(1, width), nn.Tanh()]
        for _ in range(depth - 1):
            layers.extend((nn.Linear(width, width), nn.Tanh()))
        layers.append(nn.Linear(width, 1))
        self.net = nn.Sequential(*layers)

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        return x * (PI - x) * self.net(x)


def exact_solution(x: torch.Tensor, beta: float) -> torch.Tensor:
    return x * (PI - x) * torch.tanh(beta * (x - PI / 2.0))


def derivative(value: torch.Tensor, x: torch.Tensor, *, create_graph: bool) -> torch.Tensor:
    return torch.autograd.grad(
        value, x, grad_outputs=torch.ones_like(value), create_graph=create_graph
    )[0]


def forcing(x: torch.Tensor, beta: float) -> torch.Tensor:
    y = exact_solution(x, beta)
    dy = derivative(y, x, create_graph=True)
    d2y = derivative(dy, x, create_graph=False)
    return -d2y


def metrics(model: TrialNet, x: torch.Tensor, exact: torch.Tensor) -> dict[str, float]:
    points = x.detach().clone().requires_grad_(True)
    prediction = model(points)
    gradient = derivative(prediction, points, create_graph=False)
    exact_gradient = derivative(exact_solution(points, BETA_FOR_METRICS), points, create_graph=False)
    value_error = prediction.detach() - exact.detach()
    gradient_error = gradient.detach() - exact_gradient.detach()
    l2_sq = torch.trapezoid(value_error.square().squeeze(-1), points.squeeze(-1))
    exact_l2_sq = torch.trapezoid(exact.detach().square().squeeze(-1), x.squeeze(-1))
    h1_sq = l2_sq + torch.trapezoid(gradient_error.square().squeeze(-1), points.squeeze(-1))
    return {
        "relative_l2": float(torch.sqrt(l2_sq / exact_l2_sq)),
        "h1": float(torch.sqrt(h1_sq)),
        "absolute_l2": float(torch.sqrt(l2_sq)),
    }


BETA_FOR_METRICS = 20.0


def run_case(mode_count: int, args: argparse.Namespace, initial_state: dict[str, torch.Tensor]) -> dict[str, object]:
    grid_size = max(4 * mode_count + 1, 257)
    x = torch.arange(1, grid_size + 1, dtype=torch.get_default_dtype(), device=args.device)
    x = (PI * x / (grid_size + 1)).reshape(-1, 1)
    f = forcing(x.detach().clone().requires_grad_(True), args.beta).detach()
    model = TrialNet(args.width, args.depth).to(args.device)
    model.load_state_dict(initial_state)
    model.train()
    loss_fn = FourierDualLoss(mode_count, spatial_dim=1, boundary="dirichlet", domain=PI)
    optimizer = torch.optim.Adam(model.parameters(), lr=args.learning_rate)
    started = time.perf_counter()
    history: list[dict[str, float]] = []
    for step in range(args.steps + 1):
        if step % args.log_every == 0 or step == args.steps:
            audit_x = torch.linspace(0.0, PI, args.audit_points, device=args.device).reshape(-1, 1)
            record = {"step": step, **metrics(model, audit_x, exact_solution(audit_x, args.beta))}
            history.append(record)
        if step == args.steps:
            break
        optimizer.zero_grad(set_to_none=True)
        coordinates = x.detach().clone().requires_grad_(True)
        prediction = model(coordinates)
        first = derivative(prediction, coordinates, create_graph=True)
        second = derivative(first, coordinates, create_graph=True)
        residual = (-second - f).squeeze(-1)
        loss_fn(residual).backward()
        optimizer.step()
    elapsed = time.perf_counter() - started
    final = history[-1]
    return {"modes": mode_count, "final": final, "history": history,
            "training_seconds": elapsed, "grid_points": grid_size}


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--modes", default="32,64,128,256")
    parser.add_argument("--beta", type=float, default=20.0)
    parser.add_argument("--steps", type=int, default=1000)
    parser.add_argument("--log-every", type=int, default=100)
    parser.add_argument("--audit-points", type=int, default=4097)
    parser.add_argument("--width", type=int, default=48)
    parser.add_argument("--depth", type=int, default=3)
    parser.add_argument("--learning-rate", type=float, default=2.0e-3)
    parser.add_argument("--seed", type=int, default=2026)
    parser.add_argument("--device", choices=("cpu", "cuda"), default="cuda")
    parser.add_argument("--output", type=Path, default=Path("large_gradient_modes.json"))
    return parser.parse_args()


def main() -> None:
    global BETA_FOR_METRICS
    args = parse_args()
    BETA_FOR_METRICS = args.beta
    if args.device == "cuda" and not torch.cuda.is_available():
        raise RuntimeError("CUDA requested but unavailable; pass --device cpu")
    modes = sorted({int(item) for item in args.modes.split(",") if item.strip()})
    if not modes or min(modes) < 1 or args.steps < 1:
        raise ValueError("modes must be positive and steps must be positive")
    torch.set_default_dtype(torch.float64)
    torch.manual_seed(args.seed)
    initial = TrialNet(args.width, args.depth).to(args.device).state_dict()
    results = []
    for mode_count in modes:
        print(f"[N={mode_count}] training...", flush=True)
        result = run_case(mode_count, args, initial)
        results.append(result)
        final = result["final"]
        print(f"[N={mode_count}] Relative L2={final['relative_l2']:.6e} "
              f"H1={final['h1']:.6e} time={result['training_seconds']:.3f}s", flush=True)
    output = args.output.expanduser().resolve()
    settings = {key: (str(value) if isinstance(value, Path) else value)
                for key, value in vars(args).items()}
    output.write_text(json.dumps({"problem": "large_gradient", "beta": args.beta,
                                  "settings": settings, "results": results}, indent=2),
                      encoding="utf-8")
    print("\n| modes N | final Relative L2 | final H1 | training time (s) |")
    print("|---:|---:|---:|---:|")
    for result in results:
        final = result["final"]
        print(f"| {result['modes']} | {final['relative_l2']:.6e} | "
              f"{final['h1']:.6e} | {result['training_seconds']:.3f} |")
    print(f"\nRecords written to: {output}")


if __name__ == "__main__":
    main()
